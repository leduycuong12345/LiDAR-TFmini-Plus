void displayOutput(int distance_cm,double velocity_ms)
{
  char msg[64];

  int len = snprintf(msg, sizeof(msg),
                    "Distance: %u cm | Velocity: %.3f m/s\r\n",
                    distance_cm, velocity_ms);

  HAL_UART_Transmit(&huart1,
                    (uint8_t *)msg,
                    len,
                    100);
}
